import { generateHMAC, verifyHMAC } from './crypto';
import * as logger from 'firebase-functions/logger';

/**
 * Parameters for generating a referral link
 */
export interface ReferralLinkParams {
  referralId: string;
  referrerId: string;
  loopType: string;
  experimentId?: string;
  variantId?: string;
  channel?: string;
}

/**
 * Result from link generation
 */
export interface ReferralLinkResult {
  url: string;
  provider: 'firebase' | 'branch' | 'custom';
}

/**
 * Generate signed referral link
 * 
 * Provider priority:
 * 1. Firebase Dynamic Links (DEPRECATED - shut down Aug 2025)
 * 2. Branch.io (if configured)
 * 3. Custom short domain (fallback)
 * 
 * @param params - Link generation parameters
 * @returns Generated link and provider name
 */
export async function generateReferralLink(
  params: ReferralLinkParams
): Promise<ReferralLinkResult> {
  const startTime = Date.now();
  
  try {
    // Try Branch.io if configured
    if (process.env.BRANCH_KEY) {
      const branchLink = await generateBranchLink(params);
      if (branchLink) {
        logger.info('✅ Generated Branch.io link', {
          latency: Date.now() - startTime,
        });
        return { url: branchLink, provider: 'branch' };
      }
    }
  } catch (error: any) {
    logger.warn('⚠️ Branch.io link generation failed, using fallback', {
      error: error.message,
    });
  }
  
  // Fallback: Custom short link with HMAC signature
  const customLink = generateCustomShortLink(params);
  logger.info('✅ Generated custom short link', {
    latency: Date.now() - startTime,
  });
  
  return { url: customLink, provider: 'custom' };
}

